import torch
import torch.nn as nn

class DiceLoss(nn.Module):
    def __init__(self, smooth=1e-6):
        super(DiceLoss, self).__init__()
        self.smooth = smooth

    def forward(self, inputs, targets):
        # Convert raw AI output into a probability between 0 and 1
        inputs = torch.sigmoid(inputs)

        # Flatten the 2D images into 1D arrays for fast math
        inputs = inputs.view(-1)
        targets = targets.view(-1)

        # Calculate the overlap (intersection)
        intersection = (inputs * targets).sum()

        # Calculate the Dice coefficient (similar to IoU)
        dice = (2. * intersection + self.smooth) / (inputs.sum() + targets.sum() + self.smooth)

        # The AI's goal is to minimize loss, so we subtract the score from 1
        return 1 - dice

